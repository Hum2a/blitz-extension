#!/usr/bin/env node
/**
 * Writes popup/src/lib/config.secrets.js from .env (gitignored).
 * Run via postinstall / prebuild — never commit secrets in config.js.
 */

import { existsSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import dotenv from "dotenv";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, ".env");
const outPath = join(root, "popup", "src", "lib", "config.secrets.js");

dotenv.config({ path: envPath });

const url =
  process.env.VITE_SUPABASE_URL?.trim() ||
  process.env.SUPABASE_URL?.trim() ||
  "";
const anonKey =
  process.env.VITE_SUPABASE_ANON_KEY?.trim() ||
  process.env.VITE_SUPABASE_PUBLISHABLE_KEY?.trim() ||
  process.env.SUPABASE_ANON_KEY?.trim() ||
  process.env.SUPABASE_PUBLISHABLE_KEY?.trim() ||
  "";

const contents = `// AUTO-GENERATED by scripts/sync-config-from-env.mjs — DO NOT COMMIT
// Source: .env (VITE_SUPABASE_URL + VITE_SUPABASE_ANON_KEY or VITE_SUPABASE_PUBLISHABLE_KEY)
// Regenerate: npm run config:sync

export const SUPABASE_URL = ${JSON.stringify(url)};
export const SUPABASE_ANON_KEY = ${JSON.stringify(anonKey)};
`;

writeFileSync(outPath, contents, "utf8");

if (url && anonKey) {
  console.log("config.secrets.js updated from .env (Supabase configured)");
} else if (existsSync(envPath)) {
  console.log("config.secrets.js updated (Supabase empty — add VITE_SUPABASE_* to .env)");
} else {
  console.log("config.secrets.js updated (no .env — cloud sync disabled until configured)");
}
